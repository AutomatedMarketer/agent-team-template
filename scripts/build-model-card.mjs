import { writeFile } from 'node:fs/promises'
import { fileURLToPath, pathToFileURL } from 'node:url'
import path from 'node:path'
import { loadAgents } from './lib/agents.mjs'

const repoRoot = fileURLToPath(new URL('../', import.meta.url))
const CARD_PATH = 'shared/standards/model-card.md'

const FREQUENCY = {
  orchestrator: 'Daily task sweep, and whenever you open the repo',
  research: 'Daily, or whenever you ask',
  content: 'Daily',
  editor: 'On every graded run, plus a weekly review',
  email: 'A few times a day',
  'customer-service': 'Whenever a customer asks',
  sales: 'Daily, or whenever you ask',
  security: 'Weekly, or whenever you ask'
}

export async function buildModelCard() {
  const agents = await loadAgents()
  const rows = agents.map(
    (agent) =>
      `| \`${agent.slug}\` | \`${agent.data.model}\` | ${FREQUENCY[agent.slug] ?? 'On demand'} | ${agent.data.description} |`
  )
  return [
    '<!-- Generated by scripts/build-model-card.mjs. Edit the agent files, then re-run it. -->',
    '',
    '# Which model each agent runs on',
    '',
    '**The rule:** high-frequency, well-scoped, tool-heavy work runs on Sonnet.',
    'Judgment, voice, and delegation run on Opus.',
    '',
    'Every routine run draws from your Claude plan. Put Opus on an agent that runs all day',
    'and you will spend your allowance by lunch. That is the whole reason this table exists.',
    '',
    '| Agent | Model | How often it runs | What it does |',
    '|---|---|---|---|',
    ...rows,
    '',
    'These are aliases, not version numbers. `opus` and `sonnet` follow the current',
    'recommended model, so this table stays right when a new one ships.',
    ''
  ].join('\n')
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const card = await buildModelCard()
  await writeFile(path.join(repoRoot, CARD_PATH), card, 'utf8')
  console.log(`wrote ${CARD_PATH}`)
}
